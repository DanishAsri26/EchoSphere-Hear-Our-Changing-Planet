"""Convert an ERDDAP griddap CSV of jplMURSST41anom1day (sstAnom) to EchoSphere's JSON.

AI disclosure: written with AI assistance (Claude, Anthropic).

Usage: python3 tools/csv_to_json.py input.csv data/sst-anomaly-2026-11-08.json
Output: {date, variable, units, source, lats (north→south), lons (west→east), values (row-major, null = land/ice)}
"""
import csv
import json
import math
import sys


MIN_CELLS = 30  # keeps oceans, Mediterranean, Black Sea, Caspian; drops small inland lakes


ICE_LAT = 50


def mask_sea_ice(values, lats, nc):
    """Heuristic ice mask. The SVS frame shows sea ice in grey, but the anomaly grid gives
    exactly 0 there. Without the mask, ice would sound like 'normal ocean'."""
    n = 0
    for r, la in enumerate(lats):
        if abs(la) < ICE_LAT:
            continue
        for c in range(nc):
            i = r * nc + c
            if values[i] is not None and values[i] == 0:
                values[i] = None
                n += 1
    return n


def drop_small_water_bodies(values, nr, nc, min_cells):
    """MUR also covers lakes (e.g. Bolivia, Tibet), which gave false 'ocean' extremes up to +11 C.
    Remove 8-connected water components (longitude wraps) smaller than min_cells."""
    seen = [False] * len(values)
    removed = 0
    for start in range(len(values)):
        if values[start] is None or seen[start]:
            continue
        comp, stack = [], [start]
        seen[start] = True
        while stack:
            i = stack.pop()
            comp.append(i)
            r, c = divmod(i, nc)
            for dr in (-1, 0, 1):
                for dc in (-1, 0, 1):
                    rr, cc = r + dr, (c + dc) % nc
                    if 0 <= rr < nr:
                        j = rr * nc + cc
                        if values[j] is not None and not seen[j]:
                            seen[j] = True
                            stack.append(j)
        if len(comp) < min_cells:
            for i in comp:
                values[i] = None
            removed += len(comp)
    return removed


def main(src, dst):
    with open(src, newline="") as f:
        rows = list(csv.reader(f))
    header, units, body = rows[0], rows[1], rows[2:]
    i_t, i_la, i_lo = header.index("time"), header.index("latitude"), header.index("longitude")
    i_v = header.index("sstAnom")
    lats = sorted({round(float(r[i_la]), 2) for r in body}, reverse=True)
    lons = sorted({round(float(r[i_lo]), 2) for r in body})
    li = {v: k for k, v in enumerate(lats)}
    lj = {v: k for k, v in enumerate(lons)}
    values = [None] * (len(lats) * len(lons))
    for r in body:
        v = float(r[i_v]) if r[i_v] not in ("NaN", "") else math.nan
        if not math.isnan(v):
            values[li[round(float(r[i_la]), 2)] * len(lons) + lj[round(float(r[i_lo]), 2)]] = round(v, 2)
    ice = mask_sea_ice(values, lats, len(lons))
    removed = drop_small_water_bodies(values, len(lats), len(lons), MIN_CELLS)
    date = body[0][i_t][:10]
    out = {
        "date": date,
        "variable": "sstAnom",
        "units": units[i_v],
        "source": "NASA JPL MUR SST v4.1 anomaly (climatology 2003-2014), NOAA CoastWatch ERDDAP jplMURSST41anom1day, 1-degree sample",
        "lats": lats,
        "lons": lons,
        "values": values,
        "note": f"Water bodies smaller than {MIN_CELLS} connected 1-degree cells (inland lakes) removed; {removed} cells. "
                f"Sea ice approximated: exact 0.00 anomalies poleward of {ICE_LAT} deg treated as ice ({ice} cells), "
                "because MUR fixes SST under sea ice, which makes the anomaly 0 there.",
    }
    with open(dst, "w") as f:
        json.dump(out, f, separators=(",", ":"))
    # Same data as a script, so index.html also works when opened by double-click (file://).
    with open(dst.rsplit(".", 1)[0] + ".js", "w") as f:
        f.write("/* Generated by tools/csv_to_json.py (AI-assisted). NASA JPL MUR SST anomaly. */\n")
        f.write("window.SST_DATA = " + json.dumps(out, separators=(",", ":")) + ";\n")
    ocean = [v for v in values if v is not None]
    print(f"{date}: {len(lats)}x{len(lons)} grid, {len(ocean)} ocean cells, "
          f"min {min(ocean):.2f}, max {max(ocean):.2f}, mean {sum(ocean)/len(ocean):.2f} {units[i_v]}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
